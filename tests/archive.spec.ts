import {expect,test} from '@playwright/test'
import { waitForBoard, waitForSavedGame, waitForSavedSession } from './puzzle-fixture'

test('daily archive moves between dates within UTC bounds and restores edits',async({page})=>{
 await page.clock.install({time:new Date('2026-10-21T12:00:00Z')});await page.goto('/'); await waitForBoard(page,'v2:daily:2026-10-21:classic:beginner')
 const date=page.getByLabel('Puzzle date',{exact:true})
 await expect(date).toHaveValue('2026-10-21');await expect(date).toHaveAttribute('min','2026-01-01');await expect(date).toHaveAttribute('max','2026-10-21')
 await expect(page.getByRole('button',{name:'Next day',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:'Previous day',exact:true}).click();await expect(date).toHaveValue('2026-10-20')
 await waitForBoard(page,'v2:daily:2026-10-20:classic:beginner')
 await date.fill('2026-01-01');await date.press('Tab')
 await waitForBoard(page,'v2:daily:2026-01-01:classic:beginner')
 await expect(page.getByRole('button',{name:'Previous day',exact:true})).toBeDisabled()
 const cell=page.getByRole('gridcell',{name:/empty/}).first(),id=await cell.getAttribute('data-cell')
 await cell.click();await cell.press('n');await cell.press('3')
 await waitForSavedGame(page)
 const edited=await page.getByRole('gridcell').allTextContents()
 await page.getByRole('button',{name:'Next day',exact:true}).click();await expect(date).toHaveValue('2026-01-02')
 await waitForBoard(page,'v2:daily:2026-01-02:classic:beginner')
 await page.getByRole('button',{name:'Previous day',exact:true}).click()
 await waitForBoard(page,'v2:daily:2026-01-01:classic:beginner')
 await expect(page.locator(`[data-cell="${id}"]`)).toHaveAccessibleName(/notes 3/)
 expect(await page.getByRole('gridcell').allTextContents()).toEqual(edited)
 await waitForSavedGame(page); await page.reload(); await waitForBoard(page,'v2:daily:2026-01-01:classic:beginner')
 await expect(date).toHaveValue('2026-01-01');await expect(page.locator(`[data-cell="${id}"]`)).toHaveAccessibleName(/notes 3/)
 expect(await page.getByRole('gridcell').allTextContents()).toEqual(edited)
})

test('mode selection shows real X diagonals and complete Killer cages',async({page})=>{
 await page.goto('/'); await waitForBoard(page)
 const date=await page.locator('time').getAttribute('datetime')
 const select=page.getByLabel('Game mode',{exact:true})
 await expect(select).toHaveValue('classic')
 await select.selectOption('x'); await waitForBoard(page,`v2:daily:${date}:x:beginner`)
 await expect(page.locator('.cell.diagonal')).toHaveCount(17)
 await select.selectOption('killer'); await waitForBoard(page,`v2:daily:${date}:killer:beginner`)
 const cages=page.locator('.cage-total');expect(await cages.count()).toBeGreaterThan(0)
 await expect(page.getByRole('gridcell')).toHaveCount(81)
 await expect(page.locator('.cell.given')).toHaveCount(0)
 const mapping=await page.getByRole('gridcell').evaluateAll(elements=>elements.map(element=>element.getAttribute('data-cage')))
 expect(mapping).toHaveLength(81)
 expect(mapping.every(value=>value!==null)).toBe(true)
 expect(new Set(mapping).size).toBe(await cages.count())
 await expect(page.getByRole('gridcell').first()).toHaveAccessibleName(/cage/i)
 await select.selectOption('classic'); await waitForBoard(page,`v2:daily:${date}:classic:beginner`)
 await expect(page.locator('.cell.diagonal')).toHaveCount(0)
 await expect(page.locator('.cage-total')).toHaveCount(0)
})

test('mode and archived difficulty persist, random puzzle identity stays separate',async({page})=>{
 await page.goto('/'); await waitForBoard(page)
 const date=await page.locator('time').getAttribute('datetime')
 await page.getByLabel('Game mode',{exact:true}).selectOption('x'); await waitForBoard(page,`v2:daily:${date}:x:beginner`)
 await page.getByRole('button',{name:'Intermediate',exact:true}).click(); await waitForBoard(page,`v2:daily:${date}:x:intermediate`)
 await page.getByLabel('Puzzle date',{exact:true}).fill('2026-01-15')
 await page.getByLabel('Puzzle date',{exact:true}).press('Tab')
 const dailyId='v2:daily:2026-01-15:x:intermediate'
 await waitForBoard(page,dailyId)
 const daily=await page.getByRole('gridcell').allTextContents()
 await waitForSavedGame(page); await page.reload(); await waitForBoard(page,dailyId)
 await expect(page.getByLabel('Game mode',{exact:true})).toHaveValue('x')
 await expect(page.getByLabel('Puzzle date',{exact:true})).toHaveValue('2026-01-15')
 await expect(page.getByRole('button',{name:'Intermediate',exact:true})).toHaveAttribute('aria-pressed','true')
 expect(await page.getByRole('gridcell').allTextContents()).toEqual(daily)
 await page.getByRole('button',{name:'Practice',exact:true}).click(); await waitForBoard(page,/^v2:practice:.*:x:intermediate$/)
 const randomId=await page.locator('.board-column').getAttribute('data-puzzle-id')
 const random=await page.getByRole('gridcell').allTextContents()
 await page.getByRole('button',{name:'New practice puzzle',exact:true}).click(); await waitForBoard(page,/^v2:practice:.*:x:intermediate$/)
 await expect(page.locator('.board-column')).not.toHaveAttribute('data-puzzle-id',randomId!)
 expect(await page.getByRole('gridcell').allTextContents()).not.toEqual(random)
 await waitForSavedSession(page)
 await page.getByRole('button',{name:'Daily',exact:true}).click(); await waitForBoard(page,dailyId)
 expect(await page.getByRole('gridcell').allTextContents()).toEqual(daily)
})
