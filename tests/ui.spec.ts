test('each guided lesson applies two checked deductions and persists only completed examples', async ({ page }) => {
  const { LESSONS } = await import('../src/lessons')
  expect(LESSONS).toHaveLength(8)
  await page.goto('/')
  await page.getByRole('button', { name: 'Learn', exact: true }).click()
  for (const lesson of LESSONS) {
    await page.getByRole('button', { name: new RegExp(`^${lesson.title}.*Not started`) }).click()
    await expect(page.getByRole('heading', { name: 'The rule', exact: true })).toBeVisible()
    for (let example = 0; example < 2; example++) {
      const scenario = lesson.scenarios[example]
      const board = page.getByRole('grid', { name: `${lesson.title} example ${example + 1}` })
      const target = board.locator(`[data-cell="${scenario.target}"]`)
      await target.click()
      await page.getByRole('button', { name: `Choose ${scenario.digit}`, exact: true }).click()
      await page.getByRole('radio', { name: scenario.kind === 'place' ? 'Place a number' : 'Eliminate a candidate', exact: true }).check()
      await page.getByRole('button', { name: 'Check reasoning' }).click()
      await expect(page.getByRole('heading', { name: 'That follows from the candidates.' })).toBeVisible()
      if (scenario.kind === 'place') await expect(target).toHaveAccessibleName(new RegExp(`entry ${scenario.digit}`))
      else {
        const label = await target.getAttribute('aria-label')
        expect(label?.split('candidates ')[1]?.split(', ').map(Number) || []).not.toContain(scenario.digit)
      }
      if (example === 0) {
        const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('sudoku-lessons-v1') || '{}'))
        expect(stored.passed).toContain(scenario.id)
        expect(stored.passed).not.toContain(lesson.scenarios[1].id)
        await page.getByRole('button', { name: 'Try example 2' }).click()
      }
    }
    await expect(page.getByText('Lesson complete. Both examples checked.')).toBeVisible()
    await page.getByRole('button', { name: 'Back to lessons', exact: true }).click()
    await expect(page.getByRole('button', { name: new RegExp(`^${lesson.title}.*Completed`) })).toBeVisible()
  }
})
